/** The lexicon for a project language code (`it`, `en-GB`), or `null`. */
export function lexiconFor(code: string | undefined): Lexicon | null {
  const base = (code ?? "").toLowerCase().split(/[-_]/)[0];
  if (base === "it") return ITALIAN;
  if (base === "en") return ENGLISH;
  return null;
}
