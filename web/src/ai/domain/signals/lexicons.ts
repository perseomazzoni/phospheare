// The word lists behind the signal pre-pass, one table per language. Each is
// written in its language rather than translated from another: a hedge list
// turned from English into Italian would miss half of what an Italian writer
// hedges with, and find words nobody uses.
//
// These lists find candidates, never faults. A candidate is shown to the
// model with the writer's declared prose style beside it, and the model
// decides whether each one is a fault or a choice; nothing here reaches the
// writer unjudged. So a list errs toward the words usually worth a second
// look, and leaves the judgement to the reading.

export interface Lexicon {
  /** Perception and thought verbs that can filter a sensation (`E.filter`). */
  readonly perception: readonly string[];
  /**
   * For languages that keep their subject pronouns: the subjects a perception
   * verb must follow to count, so "the saw on the bench" is not a filter.
   * Empty where the subject is usually dropped (Italian), and then the verb
   * forms themselves are specific enough.
   */
  readonly subjects: readonly string[];
  /** Qualifiers that soften a picture (`F.hedge`). */
  readonly hedges: readonly string[];
  /** Attempt and inception verbs that hide an outcome (`F.attempt`). */
  readonly attempts: readonly string[];
  /** Dialogue verbs beyond the plain ones (`G.tags`). */
  readonly tags: readonly string[];
  /**
   * How a manner adverb ends, and the words that end that way and are not
   * one (`F.manner-adverb`).
   */
  readonly adverbSuffix: string;
  readonly adverbStoplist: readonly string[];
  /** Units a character rarely thinks in (`H.jargon`). */
  readonly units: readonly string[];
  /**
   * Long function words the echo detector must not count as echoes
   * (`F.echo`); it already ignores words shorter than six letters and names.
   */
  readonly echoStoplist: readonly string[];
}

